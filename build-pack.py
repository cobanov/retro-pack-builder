#!/usr/bin/env python3
"""Build a curated game pack from a ROM archive, in ROCKNIX SD card layout.

Usage:   python3 build-pack.py <list.txt> [output-dir]
Example: RETRO=/srv/games/retro python3 build-pack.py /srv/games/retro/packs/top.txt

The archive root comes from $RETRO, or else from the list location (<root>/packs/<list>.txt).

- ROMs and covers are hardlinked, so the pack takes no extra space on the archive volume.
- If a listed game has a save in saves/, the save is copied next to the ROM.
- The output dir is rebuilt from scratch each time; copy its contents to the root of the SD card's games partition.
"""
import html
import os
import re
import shutil
import subprocess
import sys

ROMS = SAVES = MEDIA = BIOS = None  # set in main() from the archive root


def set_root(lst):
    global ROMS, SAVES, MEDIA, BIOS
    root = os.environ.get("RETRO") or os.path.join(os.path.dirname(os.path.abspath(lst)), "..")
    ROMS, SAVES, MEDIA, BIOS = (os.path.join(os.path.abspath(root), d) for d in ("roms", "saves", "media", "bios"))
    if not os.path.isdir(ROMS):
        sys.exit(f"No roms/ folder under {os.path.abspath(root)}; set RETRO to your archive root.")
MARKER = ".generated-pack"
SAVE_EXT = (".srm", ".sav", ".dsv")


def clean_name(base):
    n = re.sub(r"\s*[\(\[][^\)\]]*[\)\]]", "", base).strip()
    m = re.match(r"^(.*?), (The|A|An)( - .*)?$", n)
    if m:
        n = f"{m.group(2)} {m.group(1)}{m.group(3) or ''}"
    return n


_names = {}


def display_name(sysn, entry, base):
    """Full title from media/<system>/names.tsv (arcade short names), otherwise the cleaned file name."""
    if sysn not in _names:
        p = os.path.join(MEDIA, sysn, "names.tsv")
        _names[sysn] = dict(l.rstrip("\n").split("\t", 1) for l in open(p, encoding="utf-8") if "\t" in l) if os.path.exists(p) else {}
    return _names[sysn].get(entry) or clean_name(base)


def base_of(entry):
    return entry if os.path.isdir(os.path.join(ROMS, entry)) else os.path.splitext(entry)[0]


def read_list(path):
    items = []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        rel, _, name = (p.strip() for p in line.partition("|"))
        items.append((rel, name or None))
    return items


def link(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.isdir(src):
        for root, dirs, files in os.walk(src):
            dirs[:] = [d for d in dirs if not d.startswith("@")]
            for f in files:
                s = os.path.join(root, f)
                link(s, os.path.join(dst, os.path.relpath(s, src)))
    else:
        os.link(src, dst)


def main():
    lst = sys.argv[1]
    set_root(lst)
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.splitext(lst)[0]
    if os.path.exists(out):
        if not os.path.exists(os.path.join(out, MARKER)):
            sys.exit(f"{out} exists but is not a generated pack (marker file missing); left untouched.")
        shutil.rmtree(out)
    os.makedirs(out)
    open(os.path.join(out, MARKER), "w").write("Generated by build-pack.py, do not edit by hand.\n")

    items = read_list(lst)
    games = {}
    for rel, name in items:
        src = os.path.join(ROMS, rel)
        if not os.path.exists(src):  # listed but not in the archive (yet): skip quietly
            continue
        sysn, entry = rel.split("/", 1)
        base = base_of(rel).split("/", 1)[1]
        link(src, os.path.join(out, sysn, entry))
        art = os.path.join(MEDIA, sysn, "boxart", base + ".png")
        has_art = os.path.exists(art)
        if has_art:
            link(art, os.path.join(out, sysn, "images", base + ".png"))
        path = entry
        if os.path.isdir(src):
            # Multi-disc game: the m3u goes to the system folder, discs stay in a hidden subfolder
            m3u = os.path.join(src, base + ".m3u")
            discs = [l.strip() for l in open(m3u) if l.strip()]
            with open(os.path.join(out, sysn, base + ".m3u"), "w") as fh:
                fh.write("".join(f"{entry}/{d}\n" for d in discs))
            path = base + ".m3u"
        for ext in SAVE_EXT:
            s = os.path.join(SAVES, sysn, base + ext)
            if os.path.exists(s):
                shutil.copy2(s, os.path.join(out, sysn, base + ext))
        games.setdefault(sysn, []).append((path, name or display_name(sysn, entry, base), base if has_art else None, os.path.isdir(src), entry))

    if "neogeo" in games and os.path.exists(os.path.join(ROMS, "neogeo", "neogeo.zip")):
        link(os.path.join(ROMS, "neogeo", "neogeo.zip"), os.path.join(out, "neogeo", "neogeo.zip"))
    if os.path.isdir(BIOS):
        link(BIOS, os.path.join(out, "bios"))

    for sysn, gl in games.items():
        x = ["<?xml version=\"1.0\"?>", "<gameList>"]
        for path, name, art, is_dir, entry in sorted(gl, key=lambda g: g[1].lower()):
            x.append("\t<game>")
            x.append(f"\t\t<path>./{html.escape(path, quote=False)}</path>")
            x.append(f"\t\t<name>{html.escape(name, quote=False)}</name>")
            if art:
                x.append(f"\t\t<image>./images/{html.escape(art, quote=False)}.png</image>")
            x.append("\t</game>")
            if is_dir:
                x.append(f"\t<folder><path>./{html.escape(entry, quote=False)}</path><hidden>true</hidden></folder>")
        if sysn == "neogeo":
            x.append("\t<game><path>./neogeo.zip</path><name>Neo Geo BIOS</name><hidden>true</hidden></game>")
        x.append("</gameList>")
        open(os.path.join(out, sysn, "gamelist.xml"), "w", encoding="utf-8").write("\n".join(x) + "\n")

    size = subprocess.run(["du", "-sh", out], capture_output=True, text=True).stdout.split()[0]
    total = sum(len(g) for g in games.values())
    print(f"Pack: {out}\n{total} game{'' if total == 1 else 's'}, {size} on the SD card\n")
    for sysn in sorted(games):
        gl = games[sysn]
        print(f"  {sysn:<10} {len(gl):>3} game{'' if len(gl) == 1 else 's'}")


if __name__ == "__main__":
    main()
